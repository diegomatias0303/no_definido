import com.example.no_definido.data.HomeArea
import com.example.no_definido.ui.components.PlaceholderCard

@Composable
fun AreaSelectionScreen(
    areas: List<HomeArea>,
    onAreaSelected: (HomeArea) -> Unit,
    onBack: () -> Unit,
    modifier: Modifier = Modifier
) {
    Column(
        modifier = modifier
            .fillMaxSize()
            .background(MaterialTheme.colorScheme.background)
            .padding(16.dp)
    ) {
        Row(
            verticalAlignment = Alignment.CenterVertically,
            modifier = Modifier.fillMaxWidth()
        ) {
            IconButton(onClick = onBack) {
                Icon(
                    imageVector = Icons.AutoMirrored.Filled.ArrowBack,
                    contentDescription = "Volver",
                    tint = MaterialTheme.colorScheme.primary
                )
            }

            Spacer(modifier = Modifier.width(8.dp))

            Text(
                text = "Habitaciones del Hogar",
                fontSize = 24.sp,
                fontWeight = FontWeight.Bold,
                color = MaterialTheme.colorScheme.primary
            )
        }

        Spacer(modifier = Modifier.height(16.dp))

        LazyVerticalGrid(
            columns = GridCells.Fixed(2),
            horizontalArrangement = Arrangement.spacedBy(16.dp),
            verticalArrangement = Arrangement.spacedBy(16.dp),
            modifier = Modifier.fillMaxSize()
        ) {
            items(areas) { area ->
                PlaceholderCard(
                    title = area.name,
                    subtitle = area.description,
                    backgroundColor = Color(area.colorAccentHex).copy(alpha = 0.2f),
                    contentColor = MaterialTheme.colorScheme.onSurface,
                    onClick = { onAreaSelected(area) },
                    modifier = Modifier.height(140.dp)
                )
            }
        }
    }
}
